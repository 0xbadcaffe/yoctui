def format_rust(source: str) -> str:
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=source,
        text=True,
        check=True,
        capture_output=True,
    )
    return formatted.stdout


def command_groups(entries: list[Entry], maximum_lines: int = 300) -> list[list[Entry]]:
    groups: list[list[Entry]] = []
    current: list[Entry] = []
    current_lines = 0
    for entry in entries:
        entry_lines = len(render_command(entry).splitlines())
        if current and current_lines + entry_lines > maximum_lines:
            groups.append(current)
            current = []
            current_lines = 0
        current.append(entry)
        current_lines += entry_lines
    if current:
        groups.append(current)
    return groups


def module_name(category: Category, part: int, part_count: int) -> str:
    base = category.id.replace("-", "_")
    return base if part_count == 1 else f"{base}_part_{part:02d}"


def render_command_module(entries: list[Entry]) -> str:
    rows = "".join(render_command(entry) for entry in entries)
    return format_rust(
        "// @generated by scripts/generate-raw-catalog.py; do not edit by hand.\n"
        "use crate::*;\n\n"
        "pub(super) fn commands() -> Vec<RawCommand> {\n"
        "    vec![\n"
        f"{rows}"
        "    ]\n"
        "}\n"
    )


def generate_files() -> dict[Path, str]:
    categories, entries = read_reference()
    executable_count = sum(entry.executable for entry in entries)
    category_rows = "".join(
        f"""        RawCategory {{
            id: RawCategoryId::new({quoted(category.id)}).unwrap(),
            label: {quoted(category.label)}.into(),
            reference_heading: {quoted(category.heading)}.into(),
            kind: RawCategoryKind::{category_kind(category)},
        }},
"""
        for category in categories
    )

    generated_files: dict[Path, str] = {}
    modules: list[str] = []
    for category in categories:
        groups = command_groups(category.entries)
        for part, group in enumerate(groups, 1):
            name = module_name(category, part, len(groups))
            modules.append(name)
            generated_files[OUTPUT_DIR / f"{name}.rs"] = render_command_module(group)

    module_rows = "".join(f"mod {name};\n" for name in modules)
    extension_rows = "".join(
        f"        commands.extend({name}::commands());\n" for name in modules
    )
    parent = f"""// @generated by scripts/generate-raw-catalog.py; do not edit by hand.
use crate::*;

{module_rows}
pub const RAW_REFERENCE_SHA256: &str = {quoted(EXPECTED_SHA256)};
pub const RAW_BUILTIN_CATEGORY_COUNT: usize = {len(categories)};
pub const RAW_BUILTIN_COMMAND_COUNT: usize = {len(entries)};
pub const RAW_BUILTIN_EXECUTABLE_COUNT: usize = {executable_count};

impl RawCatalog {{
    pub fn builtin() -> Self {{
        let mut commands = Vec::with_capacity(RAW_BUILTIN_COMMAND_COUNT);
{extension_rows}        Self {{
            version: RAW_CATALOG_VERSION,
            categories: vec![
{category_rows}            ],
            commands,
        }}
    }}
}}
"""
    generated_files[OUTPUT] = format_rust(parent)
    return generated_files
